// src/logic/keyword_tables.cpp
#include "keyword_tables.h"

// ============================================================================
// 构建时注入边界
//
// 以下 BuildTables() 的实现可以由 build/keywords.json 通过 codegen 生成。
// 当前版本为手写首版，词表变更需要重新编译。当词表条目超过约 200 个、
// 或需要按领域拆分为多套配置时，再把此函数的函数体迁移到
// generated/keyword_tables_data.cpp，本文件只保留 GetKeywordTables() 的访问器。
//
// 源文件必须保存为 UTF-8，CMake 必须为 MSVC 添加 /utf-8 编译选项，
// 否则中文字面量会按系统代码页解码，在非中文 Windows 上产生乱码并导致匹配全部失效。
// ============================================================================

namespace {

KeywordTables BuildTables()
{
    KeywordTables t;

    // ------------------------------------------------------------------
    // symbolic_ops：语言层面的"要求计算"信号。
    // 注意：+ - * / = ^ 括号不在此处，由 ai_route 的 has_math_operator()
    // 逐字符扫描处理，避免把 "3-5" 中的 '-' 当作词表命中。
    // 这里补充中文运算符，否则 "3 加 5" 只能靠数字运算符识别。
    // ------------------------------------------------------------------
    t.symbolic_ops = {
        "计算", "求", "求解", "解", "解方程", "化简", "证明",
        "等于", "多少", "结果是多少", "运算", "算一下",
        "加", "减", "乘以", "除以", "乘", "除", "平方",
        "不等式", "解不等式", "方程", "区间",
    };

    // ------------------------------------------------------------------
    // tool_verbs：工具调用动词。ai_route 中优先级最高。
    // 与 open_markers 不重叠：同一个词不应同时出现在两张表中，
    // 否则路由结果依赖 switch 的求值顺序，不可审计。
    // ------------------------------------------------------------------
    t.tool_verbs = {
        "搜索", "查询", "查找", "检索",
        "打开", "读取", "保存", "写入", "下载", "上传",
        "列出", "删除文件", "重命名",
        "识别", "拍照", "录音", "听写",
        "运行命令", "执行命令", "执行程序", "运行程序",
        "回显",
    };

    // ------------------------------------------------------------------
    // open_markers：开放域标记
    // "评价" 只在此表，不在 tool_verbs——用户说"评价软件好不好用"是
    // 主观判断请求，不是工具调用。若误放入 tool_verbs，会被路由到
    // 一个不存在的 evaluate 工具，返回"当前没有可用的工具"。
    // ------------------------------------------------------------------
    t.open_markers = {
        "感觉", "觉得", "评价", "喜欢", "讨厌", "建议",
        "写一首", "写一篇", "写一段", "解释一下", "为什么", "怎么办",
    };

    // ------------------------------------------------------------------
    // action_verbs：ai_extract_keywords 生成摘要时识别的动作。
    // 比 tool_verbs 更宽——"比较""分析"不会触发工具调用，但会出现在
    // 摘要中（"17号比较了A和B"）。两张表刻意不共用。
    // ------------------------------------------------------------------
    t.action_verbs = {
        "计算", "搜索", "查询", "评价", "打开", "保存", "删除",
        "修改", "比较", "分析", "读取", "下载", "上传",
    };

    // ------------------------------------------------------------------
    // entities：领域实体词。
    // 这是最需要按项目替换的部分。当前为示例词表，实际部署时应替换为
    // 目标领域的实体集合。词表外实体不会被提取——这是确定性提取的
    // 已知限制，与"不调用 LLM"的设计选择一致。
    // ------------------------------------------------------------------
    t.entities = {
        "夹具", "模具", "家具", "软件", "行业", "网页",
        "文件", "数据库", "配置", "日志", "插件", "新闻",
    };

    // ------------------------------------------------------------------
    // time_fixed：固定时间词。
    // 数字型时间（"17号""11月""2026-11-08"）由 ai_keywords 的
    // scan_time 状态机识别，不进入词表——它们不是固定字符串，而是模式。
    // ------------------------------------------------------------------
    t.time_fixed = {
        "今天", "昨天", "明天", "前天", "后天",
        "上周", "本周", "这周", "下周",
        "上个月", "这个月", "下个月",
        "去年", "今年", "明年",
    };

    return t;
}

} // namespace

const KeywordTables& GetKeywordTables()
{
    static const KeywordTables kTables = BuildTables();
    return kTables;
}
